def localized_text(key: str, language: object, **values: object) -> str:
    """Return a pre-authored localized string; no runtime translation is used."""
    locale = normalize_language(language)
    template = UI_STRINGS.get(locale, {}).get(key)
    if template is None:
        template = UI_STRINGS[DEFAULT_LANGUAGE].get(key, key)
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


def translate_text(
    text: object,
    language: object,
    champion_names: Mapping[str, str] | None = None,
) -> str:
    source = str(text or "")
    if normalize_language(language) != "en" or not source:
        return source
    exact = ENGLISH_TEXT.get(source)
    if exact is not None:
        return exact
    if champion_names:
        stripped = source.strip()
        champion = champion_names.get(stripped)
        if champion is not None:
            start = len(source) - len(source.lstrip())
            end = len(source) - len(source.rstrip())
            return f"{source[:start]}{champion}{source[len(source) - end:] if end else ''}"
    return source
